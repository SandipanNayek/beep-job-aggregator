const FRESHER_SIGNAL_REGEX =
  /\b(intern|internship|fresher|graduate|new\s*grad|trainee|apprentice|entry[\s-]*level|associate|sde[\s-]*1|sde[\s-]*i|analyst|junior|jr\.?|campus|coordinator|specialist|executive|representative|developer|engineer|designer|operations|qa|test|support|content|marketing|research|product)\b/i;

const SENIOR_EXCLUDE_REGEX =
  /\b(staff|principal|director|vp|vice\s*president|head\s*of|distinguished|architect|manager|lead|sr\.?|senior|iii|iv|v\b)\b/i;

const HIGH_EXP_EXCLUDE_REGEX =
  /\b([4-9]|1[0-9])\+?\s*(years?|yrs?)\s*(of)?\s*(experience|exp)\b/i;

export function isIndiaLocation(rawLocation: string): boolean {
  return INDIA_LOCATION_REGEX.test(rawLocation || "");
}

export function isFresherCandidate(title: string, descriptionSnippet: string): boolean {
  if (SENIOR_EXCLUDE_REGEX.test(title)) return false;
  if (HIGH_EXP_EXCLUDE_REGEX.test(descriptionSnippet)) return false;
  if (FRESHER_SIGNAL_REGEX.test(title)) return true;

  return /\b(0[\s-]*1\s*year|0[\s-]*2\s*year|0\s*to\s*2\s*year|1[\s-]*2\s*year|freshers?|recent\s*graduate|final\s*year|2025\s*batch|2026\s*batch|2027\s*batch|no\s*prior\s*experience|entry\s*level)\b/i.test(
    descriptionSnippet
  );
}

